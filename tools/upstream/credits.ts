#!/usr/bin/env tsx
/**
 * Credits the phpMyAdmin contributors whose commits have been ported into BetterMyAdmin.
 *
 *   pnpm upstream:credits           rewrites the generated list in NOTICE
 *   pnpm upstream:credits --check   fails when NOTICE does not match the ledger (CI)
 *
 * The list is built from tools/upstream/ledger.json: every `ported` entry's author, with the
 * number of their commits we ported. Bots are left out. Run it after adding ledger entries in a
 * sync (docs/architecture/15-upstream-sync.md).
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseArgs } from 'node:util'
import { type Ledger, readLedger } from './check.ts'

const here = dirname(fileURLToPath(import.meta.url))
const notice = resolve(here, '../../NOTICE')
const BEGIN = '--- begin ported credits (generated by pnpm upstream:credits) ---'
const END = '--- end ported credits ---'

const isBot = (name: string) => /\bbot\b|\[bot\]$/i.test(name)

/** Authors of ported commits, most commits first, then by name. */
export function portedAuthors(ledger: Ledger): Array<{ name: string; commits: number }> {
  const counts = new Map<string, number>()
  for (const e of ledger.entries) {
    if (e.status !== 'ported' || !e.author || isBot(e.author)) continue
    counts.set(e.author, (counts.get(e.author) ?? 0) + 1)
  }
  return [...counts]
    .map(([name, commits]) => ({ name, commits }))
    .sort((a, b) => b.commits - a.commits || a.name.localeCompare(b.name, 'en'))
}

/** The block between the markers: one name per line, indented like the rest of NOTICE. */
export function renderCredits(ledger: Ledger): string {
  const authors = portedAuthors(ledger)
  const total = authors.reduce((n, a) => n + a.commits, 0)
  const lines = [
    BEGIN,
    'The changes of these phpMyAdmin contributors have been ported into BetterMyAdmin',
    `(${total} commits; the number after each name is how many of theirs):`,
    '',
    ...authors.map((a) => `    ${a.name} (${a.commits})`),
    END,
  ]
  return lines.join('\n')
}

function main() {
  const { values } = parseArgs({ options: { check: { type: 'boolean', default: false } } })
  const text = readFileSync(notice, 'utf8')
  const start = text.indexOf(BEGIN)
  const stop = text.indexOf(END)
  if (start < 0 || stop < start) {
    console.error(`NOTICE: the markers "${BEGIN}" and "${END}" are missing`)
    process.exit(1)
  }
  const next = text.slice(0, start) + renderCredits(readLedger()) + text.slice(stop + END.length)
  if (values.check) {
    if (next !== text) {
      console.error('NOTICE: the ported credits are out of date; run pnpm upstream:credits')
      process.exit(1)
    }
    console.log('NOTICE: ported credits are up to date')
    return
  }
  writeFileSync(notice, next)
  console.log(`NOTICE: credited ${portedAuthors(readLedger()).length} contributors`)
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main()
